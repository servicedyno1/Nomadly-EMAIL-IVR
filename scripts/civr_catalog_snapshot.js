'use strict'
// Writes the landing page's first-paint catalogue snapshot from the live public catalogue, so pricing, coverage
// and facts render before (and without) the API call. Re-run after plan, price, rate or country changes:
//   node scripts/civr_catalog_snapshot.js [http://localhost:8001]
const fs = require('fs')
const path = require('path')

const base = (process.argv[2] || 'http://localhost:8001').replace(/\/+$/, '')
const OUT = path.join(__dirname, '../frontend/src/cloudivr/pages/landing/catalogSnapshot.js')
const KEEP = ['plans', 'recommendedPlan', 'countries', 'typeNames', 'rates', 'extraNumber', 'coins', 'minTopup', 'channelLink', 'cardPayments']

async function main() {
  const res = await fetch(`${base}/api/cloudivr-web/public/catalog`)
  if (!res.ok) throw new Error(`catalog ${res.status}`)
  const c = await res.json()
  if (!Array.isArray(c.plans) || !c.plans.length || !Array.isArray(c.countries) || !c.countries.length) throw new Error('catalog looks empty — not writing the snapshot')
  const snap = Object.fromEntries(KEEP.filter(k => c[k] !== undefined).map(k => [k, c[k]]))
  // Plan feature lists are long; keep only what the landing page renders.
  snap.plans = snap.plans.map(p => ({ id: p.id, name: p.name, price: p.price, minutes: p.minutes, sms: p.sms, recommended: p.recommended, available: p.available, access: p.access, webFeatures: p.webFeatures }))
  const js = `// Generated by scripts/civr_catalog_snapshot.js on ${new Date().toISOString().slice(0, 10)} — do not edit by hand.\n` +
    `// First-paint fallback for the landing page; the live /public/catalog replaces it as soon as it answers.\n` +
    `export const CATALOG_SNAPSHOT = ${JSON.stringify(snap, null, 1).replace(/\n\s*/g, ' ')};\n`
  fs.writeFileSync(OUT, js)
  console.log(`Wrote ${OUT}: ${snap.plans.length} plans, ${snap.countries.length} countries, ${(snap.coins || []).length} coins`)
}
main().catch(e => { console.error(e.message); process.exit(1) })
