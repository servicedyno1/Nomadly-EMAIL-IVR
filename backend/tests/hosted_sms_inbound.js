// Hosted SMS inbound → web Inbox item (kind sms, meta.hosted) → reply via /notifications/:id/reply (DRY-RUN).
require('dotenv').config({ path: '/app/backend/.env' })
const { MongoClient } = require('mongodb')
const axios = require('axios')
;(async () => {
  const c = await MongoClient.connect(process.env.MONGO_URL)
  const db = c.db(process.env.DB_NAME)
  const notify = require('/app/js/cloudivr-web/notify.js')
  notify.setDb(db)
  const HS = require('/app/js/hosted-sms.js').init({ db, log: () => {}, tell: (id, t, x) => notify.push(id, t, null, x) })
  const ok = await HS.onInbound({ from: '+15125550177', to: '+13125550142', body: 'TEST inbound hosted' })
  console.log('onInbound handled:', ok)
  const n = await db.collection('webNotifications').find({ chatId: '5000000000000002', kind: 'sms' }).sort({ _id: -1 }).limit(1).next()
  console.log('notif:', JSON.stringify({ kind: n?.kind, meta: n?.meta, text: n?.text || n?.body }))
  const miss = await HS.onInbound({ from: '+15125550177', to: '+13125559999', body: 'x' })
  console.log('unknown number handled (expect false):', miss)
  const B = process.env.TEST_BASE
  const w0 = await db.collection('walletOf').findOne({ _id: '5000000000000002' })
  const lr = await axios.post(`${B}/api/cloudivr-web/auth/login`, { email: 'civr.bob@example.com', password: 'BobTest#2026' })
  const cookie = lr.headers['set-cookie'].map(s => s.split(';')[0]).join('; ')
  const r = await axios.post(`${B}/api/cloudivr-web/notifications/${n._id}/reply`, { text: 'TEST reply hosted' }, { headers: { cookie }, validateStatus: () => true })
  console.log('reply:', r.status, JSON.stringify(r.data))
  const w1 = await db.collection('walletOf').findOne({ _id: '5000000000000002' })
  console.log('charged:', Math.round(((w1.usdOut - w0.usdOut)) * 100) / 100)
  const log = await db.collection('phoneLogs').find({ phoneNumber: '+13125550142', hosted: true, direction: 'outbound' }).sort({ timestamp: -1 }).limit(1).next()
  console.log('outbound log to:', log?.to, log?.body)
  const lst = await axios.get(`${B}/api/cloudivr-web/notifications`, { headers: { cookie } })
  const it = (lst.data.items || lst.data.notifications || []).find(x => String(x.id || x._id) === String(n._id))
  console.log('notif in list w/ reply:', JSON.stringify(it?.meta || it).slice(0, 300))
  await db.collection('walletOf').updateOne({ _id: '5000000000000002' }, { $set: { usdOut: w0.usdOut } })
  await c.close(); process.exit(0)
})().catch(e => { console.error('ERR', e); process.exit(1) })
