// Monthly statement: builds last month's line payments + texts and sends once per account-month (force run).
require('dotenv').config({ path: '/app/backend/.env' })
const { MongoClient } = require('mongodb')
const S = require('/app/js/cloudivr-web/statement.js')
;(async () => {
  const c = await MongoClient.connect(process.env.MONGO_URL); const db = c.db(process.env.DB_NAME)
  const id = 'stmt-test-1', now = new Date(), last = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() - 1, 10))
  const clean = () => Promise.all([db.collection('transactions').deleteMany({ chatId: id }), db.collection('phoneLogs').deleteMany({ chatId: id }), db.collection('webAccounts').deleteMany({ _id: id }), db.collection('webStatements').deleteMany({ chatId: id }), db.collection('webPrefs').deleteMany({ _id: id })])
  await clean()
  await db.collection('webAccounts').insertOne({ _id: id, email: 'stmt-test-1@example.com', createdAt: last })
  await db.collection('transactions').insertMany([{ chatId: id, type: 'esim-purchase', amount: 75, createdAt: last, metadata: {} }, { chatId: id, type: 'esim-sms', amount: 0.05, createdAt: last, metadata: {} }])
  await db.collection('phoneLogs').insertMany([{ chatId: id, type: 'sms_out', timestamp: last, charge: 0.05 }, { chatId: id, type: 'sms', direction: 'outbound', timestamp: last, charge: 0.05 }, { chatId: id, type: 'sms', direction: 'inbound', timestamp: last }])
  const from = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() - 1, 1)), to = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), 1))
  const data = await S.build(db, id, from, to)
  const html = S.html(data, 'Test', '/settings')
  await S.runOnce(db, { log: () => {}, force: true })
  const first = await db.collection('webStatements').countDocuments({ chatId: id })
  await S.runOnce(db, { log: () => {}, force: true })
  const twice = await db.collection('webStatements').countDocuments({ chatId: id })
  await db.collection('webStatements').deleteMany({ chatId: id }); await db.collection('webPrefs').insertOne({ _id: id, statementOff: true })
  await S.runOnce(db, { log: () => {}, force: true })
  const optedOut = await db.collection('webStatements').countDocuments({ chatId: id })
  const r = { payments: data.pays.length === 1, texts: data.texts === 2, html: /−\$75\.00/.test(html) && /Texts sent/.test(html), sentOnce: first === 1 && twice === 1, optOut: optedOut === 0 }
  console.log(JSON.stringify(r)); await clean(); await c.close()
  const ok = Object.values(r).every(Boolean); console.log(ok ? 'PASS' : 'FAIL'); process.exit(ok ? 0 : 1)
})().catch(e => { console.error(e); process.exit(1) })
