#!/usr/bin/env node
// Scenario A: GB mobile — summary note, wallet pay, step validations, Back, doc type/size rules, review, submit → under_review
const H = require('./tx_payfirst_harness')
const { check, strip, last, txt } = H
const U = '990300021'
;(async () => {
  await H.connect()
  try {
    await H.mtxConfig(H.MTX_DEFAULT); await H.mtxClear()
    await H.seed(U, 'GB', 'mobile')
    const { summary, afterPay, price, payBtn } = await H.selectAndPay(U)
    const sumTxt = strip(summary.text)
    check('A1 summary has verification-after-payment note', /Verification after payment/.test(sumTxt), sumTxt)
    check('A2 note lists contact, address, 2 documents', /contact/i.test(sumTxt) && /address/i.test(sumTxt) && /2 document/i.test(sumTxt), sumTxt.match(/Verification after payment.*$/m)?.[0])
    check('A3 wallet pay button', !!payBtn, JSON.stringify(summary.buttons))
    const w1 = await H.wallet(U)
    check('A4 wallet charged (usdOut=price)', Math.abs((w1.usdOut || 0) - price) < 0.01, JSON.stringify(w1) + ' price=' + price)
    const ap = txt(afterPay)
    check('A5 Payment received + Step 2 of 2 + first prompt', /Payment received: \$/.test(ap) && /Step 2 of 2/.test(ap) && /name/i.test(ap), ap.slice(0, 400))
    const s0 = await H.sess(U)
    check('A6 session collecting with payment.refund usd', s0 && s0.payment?.refund?.currency === 'usd' && s0.payment.refund.amount === price && s0.payment.paymentMethod, JSON.stringify(s0?.payment))
    check('A7 state.action=cpTxReg', (await H.stateOf(U)).action === 'cpTxReg')
    // name validation
    let r = await H.sendText(U, 'Maria')
    check('A8 single-word name rejected', (await H.sess(U)).steps[(await H.sess(U)).idx] === 'name' && /first and last|full name|last name/i.test(strip(last(r).text)), strip(last(r).text))
    r = await H.sendText(U, 'Maria Jansen')
    let s = await H.sess(U)
    check('A9 valid name accepted → business', s.steps[s.idx] === 'business' && (last(r).buttons || []).includes('👤 Individual (no company)') && (last(r).buttons || []).includes('⬅️ Back'), JSON.stringify(last(r).buttons))
    r = await H.sendText(U, '👤 Individual (no company)')
    s = await H.sess(U)
    check('A10 Individual → phone step', s.steps[s.idx] === 'phone' && s.profile.isIndividual === true, s.steps[s.idx])
    r = await H.sendText(U, 'abc123')
    s = await H.sess(U)
    check('A11 bad phone rejected', s.steps[s.idx] === 'phone' && /phone/i.test(strip(last(r).text)), strip(last(r).text))
    r = await H.sendText(U, '⬅️ Back')
    s = await H.sess(U)
    check('A12 Back → business step', s.steps[s.idx] === 'business', s.steps[s.idx] + ' :: ' + strip(last(r).text).slice(0, 120))
    check('A12b still in cpTxReg after Back', (await H.stateOf(U)).action === 'cpTxReg')
    await H.sendText(U, '👤 Individual (no company)')
    await H.sendText(U, '+44 7700 900123')
    s = await H.sess(U)
    check('A13 phone normalized', s.profile.phone === '+447700900123', s.profile.phone)
    await H.sendText(U, '10 Downing Street'); await H.sendText(U, 'London'); await H.sendText(U, '⏭ Skip')
    await H.sendText(U, 'SW1A 2AA')
    r = await H.sendText(U, 'ZZ')
    s = await H.sess(U)
    check('A14 invalid country rejected', s.steps[s.idx] === 'country', s.steps[s.idx])
    r = await H.sendText(U, 'GB', { max: 25000, settle: 2500 })
    s = await H.sess(U)
    check('A15 ISO code GB accepted', s.address.country === 'GB' && s.steps[s.idx] !== 'country', JSON.stringify(s.address) + ' step=' + s.steps[s.idx])
    console.log('  after country:', s.steps[s.idx], strip(last(r).text).slice(0, 200).replace(/\n/g, ' ⏎ '), JSON.stringify(last(r).buttons))
    if (s.steps[s.idx] === 'addr_check') {
      check('A16 addr_check has Keep/Re-enter buttons', (last(r).buttons || []).some(b => /Keep/.test(b)) && (last(r).buttons || []).some(b => /Re-enter|enter/i.test(b)), JSON.stringify(last(r).buttons))
    }
    // walk to first doc
    s = await H.walkTo(U, 'doc:1cfde0b1-f85e-4444-9c1a-413cfa3f079f')
    check('A17 reached first document step', s && s.steps[s.idx].startsWith('doc:'), s && s.steps[s.idx])
    r = await H.sendDoc(U, { file_name: 'id.zip', mime_type: 'application/zip', file_size: 1000 })
    s = await H.sess(U)
    check('A18 zip document rejected', s.steps[s.idx].startsWith('doc:1cfde0b1') && !s.docs['1cfde0b1-f85e-4444-9c1a-413cfa3f079f'], strip(last(r).text).slice(0, 150))
    r = await H.sendDoc(U, { file_name: 'id.pdf', mime_type: 'application/pdf', file_size: 11 * 1024 * 1024 })
    s = await H.sess(U)
    check('A19 >10MB pdf rejected', s.steps[s.idx].startsWith('doc:1cfde0b1') && /10/.test(strip(last(r).text)), strip(last(r).text).slice(0, 150))
    r = await H.sendText(U, 'here is my id')
    s = await H.sess(U)
    check('A20 text on doc step → asks for file', s.steps[s.idx].startsWith('doc:1cfde0b1'), strip(last(r).text).slice(0, 150))
    r = await H.sendDoc(U, { file_name: 'id.pdf', mime_type: 'application/pdf', file_size: 50000 })
    s = await H.sess(U)
    check('A21 pdf accepted → next doc', s.steps[s.idx].startsWith('doc:b0197fa1') && s.docs['1cfde0b1-f85e-4444-9c1a-413cfa3f079f']?.file_id, s.steps[s.idx])
    r = await H.sendPhoto(U)
    s = await H.sess(U)
    check('A22 photo accepted → review', s.steps[s.idx] === 'review', s.steps[s.idx])
    const rv = last(r)
    check('A23 review buttons Submit/Start over/Cancel', ['✅ Submit for verification', '🔄 Start over', '❌ Cancel'].every(b => (rv.buttons || []).includes(b)), JSON.stringify(rv.buttons))
    check('A24 review summary shows name/phone/address/docs', /Maria Jansen/.test(strip(rv.text)) && /\+447700900123/.test(strip(rv.text)) && /Downing/.test(strip(rv.text)) && /2/.test(strip(rv.text)), strip(rv.text).slice(0, 500))
    // Back from review → previous doc
    r = await H.sendText(U, '⬅️ Back')
    s = await H.sess(U)
    check('A25 Back on review → last doc step (Back not offered on review keyboard, but text handled)', s.steps[s.idx].startsWith('doc:'), s.steps[s.idx])
    await H.sendPhoto(U)
    r = await H.sendText(U, '✅ Submit for verification', { max: 30000, settle: 3000 })
    console.log('  submit →', txt(r).slice(0, 400).replace(/\n/g, ' ⏎ '))
    const done = await H.anySess(U)
    check('A26 session ordered', done?.status === 'ordered', done?.status + ' ' + (done?.lastError || ''))
    const pend = await H.db.collection('telnyxPendingOrders').findOne({ chatId: U })
    check('A27 pending order under_review w/ refund', pend?.status === 'under_review' && pend?.refund?.amount === price, JSON.stringify(pend))
    const tc = await H.mtxCalls()
    const ord = tc.find(c => c.method === 'POST' && c.path === '/number_orders')
    const rr = ord?.body?.phone_numbers?.[0]?.regulatory_requirements || []
    const docPosts = tc.filter(c => c.method === 'POST' && c.path === '/documents')
    const addrPost = tc.find(c => c.method === 'POST' && c.path === '/addresses')
    console.log('  order body:', JSON.stringify(ord?.body).slice(0, 900))
    check('A28 order has address id + 2 doc ids + textual', rr.some(x => /^addr-mock/.test(x.field_value)) && rr.filter(x => /^doc-mock/.test(x.field_value)).length === 2 && rr.length >= 5, JSON.stringify(rr))
    check('A29 2 documents uploaded, address created', docPosts.length === 2 && !!addrPost, `docs=${docPosts.length} addr=${!!addrPost}`)
    check('A30 no messaging_profile_id for voice-only', ord && !ord.body.messaging_profile_id, JSON.stringify(ord?.body))
    check('A31 user told verification in progress', /verification in progress/i.test(txt(r)), txt(r))
    const w2 = await H.wallet(U)
    check('A32 wallet not refunded', Math.abs((w2.usdIn || 0) - 500) < 0.01, JSON.stringify(w2))
    check('A33 action reset to none', (await H.stateOf(U)).action !== 'cpTxReg', (await H.stateOf(U)).action)
    const order = (await H.calls(U, 0)).map(c => strip(c.text))
    const iSub = order.findIndex(t => /Submitting|submitting|Sending/i.test(t)); const iRev = order.findIndex(t => /verification in progress/i.test(t))
    check('A34 messages in order (submitting before under-review)', iSub === -1 || iSub < iRev, `${iSub} ${iRev}`)
  } catch (e) { console.log('ERROR', e.stack) } finally {
    if (!process.env.KEEP) await H.cleanup(U)
    H.summaryOut(); await H.close()
  }
})()
