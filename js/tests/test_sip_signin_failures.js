// node js/tests/test_sip_signin_failures.js — failed sign-ins reported by the SIP server show on the number's badge and the admin list
require('dotenv').config({ path: require('path').join(__dirname, '../../backend/.env') })
const assert = require('assert')
const { MongoClient } = require('mongodb')
const sp = require('../sip-presence')
;(async () => {
  const c = await MongoClient.connect(process.env.MONGO_URL); const db = c.db(`sipfail_test_${Date.now()}`)
  try {
    const t0 = new Date('2026-11-18T12:00:00Z'), m = (x) => new Date(t0.getTime() + x * 60000)
    const num = { phoneNumber: '+15550002222', status: 'active', sipUsername: 'cvfail01', extraSip: [{ username: 'cvfail02' }] }
    await db.collection('webAccounts').insertOne({ _id: 777001, email: 'owner@example.com' })
    await db.collection('phoneNumbersOf').insertMany([{ _id: 777001, val: { numbers: [num, { phoneNumber: '+15550003333', status: 'released', sipUsername: 'cvgone' }] } }, { _id: 'tg55', val: { numbers: [{ phoneNumber: '+15550004444', status: 'active', sipUsername: 'cvok01' }] } }])
    await sp.record(db, 'cvfail01', 600, 'Zoiper', t0)
    assert.strictEqual((await sp.status(db, num, m(1))).lastFailure, null, 'no failure yet')
    assert.strictEqual(await sp.fail(db, 'cvfail01', 'nonsense', 'Zoiper', m(2)), false, 'unknown reason ignored')
    assert.strictEqual(await sp.fail(db, 'cvfail01', 'password', 'cloudivr-selftest', m(2)), false, 'our own checks ignored')
    await sp.fail(db, 'cvfail02', 'password', 'Linphone', m(3))
    let s = await sp.status(db, num, m(4))
    assert.strictEqual(s.state, 'signed_in'); assert.strictEqual(s.lastFailure.reason, 'password'); assert.strictEqual(s.lastFailure.login, 'cvfail02'); assert.ok(/password/i.test(s.lastFailure.text))
    await sp.fail(db, 'cvfail02', 'locked', 'Linphone', m(5))
    assert.strictEqual((await sp.status(db, num, m(6))).lastFailure.reason, 'locked', 'newest reason wins')
    await sp.record(db, 'cvfail02', 600, 'Linphone', m(7))
    assert.strictEqual((await sp.status(db, num, m(8))).lastFailure, null, 'a good sign-in clears it')
    await sp.fail(db, 'cvfail01', 'password', 'Zoiper', m(20))
    assert.strictEqual((await sp.status(db, num, m(20 + 25 * 60))).lastFailure, null, 'gone after 24 h')
    await db.collection('sipStaleNotices').insertOne({ _id: 'cvold9', at: m(30), chatId: '777001', phoneNumber: num.phoneNumber, current: 'cvfail01' })
    s = await sp.status(db, num, m(31))
    assert.strictEqual(s.lastFailure.reason, 'old_login'); assert.ok(s.lastFailure.text.includes('cvold9'))
    await sp.record(db, 'cvok01', 600, 'MicroSIP', m(30))
    const o = await sp.overview(db, m(31))
    assert.strictEqual(o.total, 2, 'released numbers are left out'); assert.strictEqual(o.signedIn, 1); assert.strictEqual(o.failing, 1)
    assert.strictEqual(o.items[0].login, 'cvfail01', 'problems first'); assert.strictEqual(o.items[0].email, 'owner@example.com'); assert.strictEqual(o.items[0].lastFailure.reason, 'password')
    assert.strictEqual(o.items[1].state, 'signed_in'); assert.strictEqual(o.items[1].email, null)
    console.log('sip sign-in failures: all passed')
  } finally { await db.dropDatabase(); await c.close() }
})().catch(e => { console.error(e); process.exit(1) })
